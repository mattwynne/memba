  defp assign_conversion_from_params(socket, request_id) do
    case active_request(request_id) do
      %Request{} = request ->
        params = conversion_params_from_request(request)

        socket
        |> clear_rejection()
        |> assign(:inactive_conversion_request_id, nil)
        |> assign(:converting_request, request)
        |> assign(:conversion_slug_autogenerated?, true)
        |> assign_conversion_form(params)

      nil ->
        socket
        |> clear_rejection()
        |> clear_conversion()
        |> assign(:inactive_conversion_request_id, request_id || "unknown")
        |> refresh_active_requests()
        |> put_flash(:error, "That request is no longer active.")
    end
  end

  defp assign_active_requests(socket, requests, opts \\ []) do
    stream_opts =
      [dom_id: &"request-row-#{&1.request_id}"]
      |> Keyword.merge(Keyword.take(opts, [:reset]))

    socket
    |> assign(:active_request_count, length(requests))
    |> stream(:active_requests, requests, stream_opts)
  end

  defp active_request(request_id) do
    case Onboarding.get_request(request_id) do
      %Request{} = request ->
        if request.status == Request.status_active(), do: request

      _request ->
        nil
    end
  end

  defp assign_rejection_form(socket, %Ecto.Changeset{} = changeset) do
    assign(socket, :rejection_form, to_form(changeset, as: :rejection))
  end

  defp assign_conversion_form(socket, club_params, target \\ []) do
    {club_params, slug_autogenerated?} =
      ClubSlugForm.suggest_params(
        club_params,
        target,
        socket.assigns.conversion_slug_autogenerated?
      )

    socket
    |> assign(:conversion_form, ClubSlugForm.to_form(club_params))
    |> assign(:conversion_slug_autogenerated?, slug_autogenerated?)
    |> assign(:conversion_slug_feedback, ClubSlugForm.feedback(nil, Map.get(club_params, "slug")))
  end

  defp clear_rejection(socket) do
    socket
    |> assign(:rejecting_request, nil)
    |> assign(:rejection_form, nil)
  end

  defp clear_conversion(socket) do
    socket
    |> assign(:converting_request, nil)
    |> assign(:conversion_form, nil)
    |> assign(:conversion_slug_autogenerated?, true)
    |> assign(:conversion_slug_feedback, ClubSlugForm.feedback(nil, ""))
  end

  defp request_no_longer_active(socket) do
    socket
    |> clear_rejection()
    |> clear_conversion()
    |> refresh_active_requests()
    |> put_flash(:error, "That request is no longer active.")
  end

  defp refresh_active_requests(socket) do
    assign_active_requests(socket, Onboarding.list_active_requests(), reset: true)
  end

  defp decrement_active_request_count(socket) do
    assign(socket, :active_request_count, max(socket.assigns.active_request_count - 1, 0))
  end

  defp assign_request_converted(socket, %{request: %Request{} = converted_request} = conversion) do
    socket
    |> clear_conversion()
    |> decrement_active_request_count()
    |> stream_delete(:active_requests, converted_request)
    |> push_patch(to: ~p"/admin/requests")
    |> put_flash(
      :info,
      "Converted request for #{converted_request.requested_club_name}."
    )
    |> maybe_put_welcome_email_flash(conversion)
  end

  defp maybe_put_welcome_email_flash(socket, %{welcome_email: :ok}), do: socket

  defp maybe_put_welcome_email_flash(socket, %{welcome_email: {:error, reason}}) do
    put_flash(socket, :error, "Welcome email could not be delivered: #{format_reason(reason)}")
  end

  defp maybe_put_welcome_email_flash(socket, _conversion), do: socket

  defp current_staff_email(socket) do
    socket.assigns.current_identity_email
  end

  defp conversion_params_from_request(%Request{} = request) do
    %{"name" => request.requested_club_name, "slug" => ""}
  end

  defp format_reason(%Ecto.Changeset{} = changeset) do
    changeset
    |> Ecto.Changeset.traverse_errors(fn {message, opts} ->
      Regex.replace(~r"%{(\w+)}", message, fn _, key ->
        opts |> Keyword.get(String.to_existing_atom(key), key) |> to_string()
      end)
    end)
    |> inspect()
  end

  defp format_reason(reason), do: reason |> inspect() |> String.replace("_", " ")

  defp requester_initials(name) when is_binary(name) do
    name
    |> String.split(~r/\s+/, trim: true)
    |> Enum.take(2)
    |> Enum.map(&String.first/1)
    |> Enum.join()
    |> String.upcase()
    |> case do
      "" -> "RQ"
      initials -> initials
    end
  end

  defp requester_initials(_name), do: "RQ"

  defp format_submitted_at(%DateTime{} = inserted_at) do
    Calendar.strftime(inserted_at, "%Y-%m-%d %H:%M:%S UTC")
  end

  defp format_submitted_at(nil), do: "Unknown"
end
