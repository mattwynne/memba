defmodule MembaWeb.Admin.RequestsLive.Index do
  use MembaWeb, :live_view

  alias Memba.Onboarding
  alias Memba.Onboarding.Request
  alias MembaWeb.Admin.ClubSlugForm

  @impl Phoenix.LiveView
  def mount(_params, _session, socket) do
    requests = Onboarding.list_active_requests()

    socket =
      socket
      |> assign(:rejecting_request, nil)
      |> assign(:rejection_form, nil)
      |> assign(:converting_request, nil)
      |> assign(:conversion_form, nil)
      |> assign(:conversion_slug_autogenerated?, true)
      |> assign(:conversion_slug_feedback, ClubSlugForm.feedback(nil, ""))
      |> assign(:inactive_conversion_request_id, nil)
      |> assign_active_requests(requests)

    {:ok, socket}
  end

  @impl Phoenix.LiveView
  def handle_params(params, _uri, socket) do
    case socket.assigns.live_action do
      :convert ->
        {:noreply, assign_conversion_from_params(socket, Map.get(params, "request_id"))}

      _index ->
        {:noreply,
         socket
         |> clear_conversion()
         |> assign(:inactive_conversion_request_id, nil)}
    end
  end

  @impl Phoenix.LiveView
  def handle_event("start_rejection", %{"request-id" => request_id}, socket) do
    case active_request(request_id) do
      %Request{} = request ->
        {:noreply,
         socket
         |> clear_conversion()
         |> assign(:rejecting_request, request)
         |> assign_rejection_form(Onboarding.change_rejection(request))}

      nil ->
        {:noreply, request_no_longer_active(socket)}
    end
  end

  def handle_event("cancel_rejection", _params, socket) do
    {:noreply, clear_rejection(socket)}
  end

  def handle_event(
        "reject_request",
        params,
        %{assigns: %{rejecting_request: %Request{} = request}} = socket
      ) do
    attrs = Map.get(params, "rejection", %{})

    case Onboarding.reject_request(request.request_id, attrs,
           staff_email: current_staff_email(socket)
         ) do
      {:ok, %Request{} = rejected_request} ->
        {:noreply,
         socket
         |> clear_rejection()
         |> decrement_active_request_count()
         |> stream_delete(:active_requests, rejected_request)
         |> put_flash(:info, "Rejected request for #{rejected_request.requested_club_name}.")}

      {:error, %Ecto.Changeset{} = changeset} ->
        {:noreply, assign_rejection_form(socket, changeset)}

      {:error, _reason} ->
        {:noreply, request_no_longer_active(socket)}
    end
  end

  def handle_event("reject_request", _params, socket) do
    {:noreply, request_no_longer_active(socket)}
  end

  def handle_event("start_conversion", %{"request-id" => request_id}, socket) do
    case active_request(request_id) do
      %Request{} = request ->
        params = conversion_params_from_request(request)

        {:noreply,
         socket
         |> clear_rejection()
         |> assign(:converting_request, request)
         |> assign(:conversion_slug_autogenerated?, true)
         |> assign_conversion_form(params)}

      nil ->
        {:noreply, request_no_longer_active(socket)}
    end
  end

  def handle_event("suggest_conversion_slug", %{"club" => club_params} = params, socket) do
    target = Map.get(params, "_target", [])

    {:noreply, assign_conversion_form(socket, club_params, target)}
  end

  def handle_event("cancel_conversion", _params, socket) do
    {:noreply, push_patch(socket, to: ~p"/admin/requests")}
  end

  def handle_event(
        "convert_request",
        %{"club" => club_params},
        %{assigns: %{converting_request: %Request{} = request}} = socket
      ) do
    feedback = ClubSlugForm.feedback(nil, Map.get(club_params, "slug"))

    if feedback.valid do
      case Onboarding.convert_request_to_club(request.request_id, club_params,
             staff_email: current_staff_email(socket)
           ) do
        {:ok, conversion} ->
          {:noreply, assign_request_converted(socket, conversion)}

        {:error, %Ecto.Changeset{} = changeset} ->
          {:noreply,
           socket
           |> put_flash(:error, "Could not convert request: #{format_reason(changeset)}")
           |> assign_conversion_form(club_params, ["club", "slug"])}

        {:error, reason} when reason in [:not_active, :not_found] ->
          {:noreply, request_no_longer_active(socket)}

        {:error, reason} ->
          {:noreply,
           socket
           |> put_flash(:error, "Could not convert request: #{format_reason(reason)}")
           |> assign_conversion_form(club_params, ["club", "slug"])}
      end
    else
      {:noreply,
       socket
       |> put_flash(:error, "Choose a valid and available slug before converting this request.")
       |> assign_conversion_form(club_params, ["club", "slug"])}
    end
  end

  def handle_event("convert_request", _params, socket) do
    {:noreply, request_no_longer_active(socket)}
  end

